"""Populate a local wheelhouse from Aliyun mirrors, verifying original uv.lock hashes.

Run using a Python 3.11 interpreter with packaging installed. The requirements
file is generated by uv export --frozen; only packages selected for this machine
are fetched. The source lock file and pinned Git revision remain unchanged.
"""

import argparse
from concurrent.futures import ThreadPoolExecutor
import hashlib
from pathlib import Path
import tomllib
from urllib.parse import unquote
from urllib.parse import urlsplit
from urllib.request import ProxyHandler
from urllib.request import build_opener

from packaging.requirements import Requirement
from packaging.tags import sys_tags
from packaging.utils import parse_wheel_filename


def populate(lock: Path, requirements: Path, output: Path) -> None:
    output.mkdir(parents=True, exist_ok=True)
    selected = {}
    for line in requirements.read_text().splitlines():
        if not line or line.startswith(("#", " ", "-")):
            continue
        requirement = Requirement(line)
        if requirement.marker is None or requirement.marker.evaluate():
            selected[requirement.name] = requirement
    tags = {tag: index for index, tag in enumerate(sys_tags())}
    artifacts = []
    for package in tomllib.loads(lock.read_text())["package"]:
        requirement = selected.get(package["name"])
        if requirement is None or requirement.url or package["version"] not in requirement.specifier:
            continue
        wheels = []
        for wheel in package.get("wheels", []):
            filename = unquote(urlsplit(wheel["url"]).path.rsplit("/", 1)[-1])
            compatible = parse_wheel_filename(filename)[3] & tags.keys()
            if compatible:
                wheels.append((min(tags[tag] for tag in compatible), wheel))
        if wheels:
            artifacts.append(min(wheels, key=lambda item: item[0])[1])
        elif "sdist" in package:
            artifacts.append(package["sdist"])
        else:
            raise ValueError(f"No compatible artifact for {package['name']}")

    def fetch(artifact: dict) -> None:
        url = artifact["url"]
        if url.startswith("https://files.pythonhosted.org/packages/"):
            mirror = url.replace("https://files.pythonhosted.org/", "http://mirrors.cloud.aliyuncs.com/pypi/", 1)
        elif urlsplit(url).hostname in ("download.pytorch.org", "download-r2.pytorch.org"):
            mirror = "http://mirrors.cloud.aliyuncs.com/pytorch-wheels/" + urlsplit(url).path.removeprefix("/whl/")
        else:
            raise ValueError(f"Unsupported artifact source: {url}")
        destination = output / unquote(urlsplit(url).path.rsplit("/", 1)[-1])
        expected = artifact["hash"].removeprefix("sha256:")
        if destination.exists():
            with destination.open("rb") as stream:
                if hashlib.file_digest(stream, "sha256").hexdigest() == expected:
                    return
            raise ValueError(f"Existing wheel has wrong hash: {destination}")
        partial = destination.with_name(destination.name + ".partial")
        digest = hashlib.sha256()
        opener = build_opener(ProxyHandler({}))
        with opener.open(mirror, timeout=120) as response, partial.open("wb") as stream:
            while chunk := response.read(1024 * 1024):
                stream.write(chunk)
                digest.update(chunk)
        if digest.hexdigest() != expected:
            raise ValueError(f"Mirror hash mismatch: {destination.name}")
        partial.rename(destination)
        print(f"Verified: {destination.name}", flush=True)

    with ThreadPoolExecutor(max_workers=6) as executor:
        list(executor.map(fetch, artifacts))
    print(f"READY: {len(artifacts)} hash-verified locked artifacts in {output}", flush=True)


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--lock", type=Path, default=Path("uv.lock"))
    parser.add_argument("--requirements", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    populate(args.lock, args.requirements, args.output)


if __name__ == "__main__":
    main()
